"""Pooled particle system.

Three decisions drive this file:

1. **Nothing is allocated per particle during play.** The pool of particle
   objects is built once at construction and reused forever; emitting writes
   over a dead slot's fields. A burst of 300 short-lived objects per second is
   enough to earn a generational GC pause on a mid-range Android phone, and a
   pause is a visible hitch exactly when the screen is busiest -- which is
   exactly when a player notices.

2. **Everything is in world units.** Position, velocity, gravity and size are
   authored against the 1080-unit-tall world and converted at draw time, so a
   flap puff is the same size relative to the bird on every device.

3. **Drawing is cache-first.** Scaling and tinting a sprite per particle per
   frame would be hundreds of `smoothscale` calls a frame. Sizes snap to
   buckets, colours to sixteen levels per channel and rotations to 15 degrees,
   so a whole effect's visible variety costs a few hundred cached surfaces --
   and the quantisation is invisible on a soft, moving, fading sprite.

Art may not exist yet (it is generated by a separate build step), so each
sprite falls back to a procedurally drawn texture rather than the magenta
"missing asset" placeholder: a hundred magenta squares in additive blend would
drown the screen, and the fallbacks let the juice be tuned before the art
lands. Nothing here asserts a file exists.
"""
from __future__ import annotations

import math
import random
import weakref
from typing import TYPE_CHECKING, Any, Dict, List, Optional, Tuple

import pygame

from .. import assets
from .easing import EaseFn, clamp01, in_cubic, in_quad, linear, out_cubic, out_quad

if TYPE_CHECKING:  # pragma: no cover - typing only
    from ..display import Viewport

__all__ = ["ParticleSystem", "PRESETS", "SPRITES", "invalidate"]

# Mirrors tools/manifest.PARTICLES. The manifest is a build-time module (it is
# not shipped in the APK), so the runtime keeps its own copy of the contract
# rather than importing across that boundary.
SPRITES: Tuple[str, ...] = (
    "fx_soft", "fx_spark", "fx_star", "fx_feather", "fx_ring", "fx_dust",
)
_SPRITE_SOURCE_SIZE = {
    "fx_soft": 96, "fx_spark": 72, "fx_star": 96,
    "fx_feather": 96, "fx_ring": 256, "fx_dust": 80,
}

# Draw-surface cache budget. Every entry is a scaled, tinted sprite (tens of
# KB), so this is a memory ceiling as much as a speed one. The quantisation
# steps below exist to keep the working set comfortably underneath it: an
# effect that overflows the cache every frame rebuilds its surfaces every
# frame, which is far slower than not caching at all.
_CACHE_LIMIT = 640
_ROT_STEP = 15.0            # degrees per cached rotation, 24 steps around
_COLOR_STEP = 16            # colour quantisation, 16 levels per channel
_RECYCLE_SAMPLE = 16        # slots examined when stealing from a full pool


# --------------------------------------------------------------------------
# textures
# --------------------------------------------------------------------------
_textures: Dict[str, pygame.Surface] = {}
_warned: set = set()
# Bumped by invalidate(); live systems compare against it and drop their own
# derived surfaces, which a module-level clear cannot reach.
_generation = 0
# Every constructed system, weakly: invalidate() has to reach the per-system
# caches, and a scene that has been torn down must never be kept alive by the
# effects library it happened to use.
_live: "weakref.WeakSet[ParticleSystem]" = weakref.WeakSet()


def _blank(size: int) -> pygame.Surface:
    return pygame.Surface((size, size), pygame.SRCALPHA)


def _radial(size: int, power: float, peak: int = 255) -> pygame.Surface:
    """A soft disc drawn as nested circles -- cheaper than a per-pixel loop and
    indistinguishable once it has been scaled down to particle size."""
    surf = _blank(size)
    r = size // 2
    for i in range(r, 0, -1):
        f = 1.0 - i / r
        a = int(peak * math.pow(f, power))
        pygame.draw.circle(surf, (255, 255, 255, a), (r, r), i)
    return surf


def _ring_texture(size: int) -> pygame.Surface:
    """A soft annulus: nested *filled* discs, largest first.

    Outlined circles look like the obvious way to draw a ring and are a trap --
    pygame's outlines overwrite rather than blend, and consecutive radii leave
    a thin, dim, aliased band instead of a smooth annulus. Filling inwards
    makes every pixel's final alpha the value for its own radius.
    """
    surf = _blank(size)
    c = size // 2
    r = c - 1
    for i in range(r, 0, -1):
        d = (i / r - 0.78) / 0.15
        pygame.draw.circle(surf, (255, 255, 255, int(255 * math.exp(-0.5 * d * d))), (c, c), i)
    return surf


def _spark_texture(size: int) -> pygame.Surface:
    surf = _blank(size)
    c = size * 0.5
    short = size * 0.055
    # Spikes first, core second: pygame.draw writes pixels instead of blending,
    # so the bright core has to land on top or the cross would punch a hole.
    pygame.draw.polygon(surf, (255, 255, 255, 150),
                        [(c, 0), (c + short, c), (c, size), (c - short, c)])
    pygame.draw.polygon(surf, (255, 255, 255, 150),
                        [(0, c), (c, c - short), (size, c), (c, c + short)])
    core = int(size * 0.17)
    for i in range(core, 0, -1):
        f = 1.0 - i / core
        pygame.draw.circle(surf, (255, 255, 255, int(255 * (0.35 + 0.65 * f * f))),
                           (int(c), int(c)), i)
    return surf


def _star_texture(size: int) -> pygame.Surface:
    surf = _blank(size)
    c = size * 0.5
    glow = int(size * 0.42)
    for i in range(glow, 0, -1):
        f = 1.0 - i / glow
        pygame.draw.circle(surf, (255, 255, 255, int(70 * f * f)), (int(c), int(c)), i)
    pts: List[Tuple[float, float]] = []
    for i in range(10):
        ang = -math.pi * 0.5 + i * math.pi / 5.0
        rad = c * 0.92 if i % 2 == 0 else c * 0.40
        pts.append((c + math.cos(ang) * rad, c + math.sin(ang) * rad))
    pygame.draw.polygon(surf, (255, 255, 255, 255), pts)
    return surf


def _feather_texture(size: int) -> pygame.Surface:
    surf = _blank(size)
    top: List[Tuple[float, float]] = []
    bottom: List[Tuple[float, float]] = []
    spine: List[Tuple[float, float]] = []
    steps = 20
    for i in range(steps + 1):
        t = i / steps
        x = (0.10 + 0.80 * t) * size
        # A gentle S in the spine is what separates a feather from a leaf.
        y = (0.74 - 0.48 * t + 0.09 * math.sin(t * math.pi)) * size
        w = size * 0.155 * math.sin(math.pi * math.pow(t, 0.72))
        spine.append((x, y))
        top.append((x, y - w))
        bottom.append((x, y + w))
    pygame.draw.polygon(surf, (255, 255, 255, 225), top + bottom[::-1])
    pygame.draw.lines(surf, (255, 255, 255, 255), False, spine, max(1, size // 40))
    return surf


def _procedural(name: str) -> pygame.Surface:
    size = _SPRITE_SOURCE_SIZE.get(name, 64)
    if name == "fx_ring":
        return _ring_texture(size)
    if name == "fx_spark":
        return _spark_texture(size)
    if name == "fx_star":
        return _star_texture(size)
    if name == "fx_feather":
        return _feather_texture(size)
    if name == "fx_dust":
        return _radial(size, 1.15, 215)
    return _radial(size, 2.0)


def _texture(name: str) -> pygame.Surface:
    """The luminance sprite for `name`: the shipped PNG if present, else a
    procedural stand-in of the same authored size."""
    surf = _textures.get(name)
    if surf is not None:
        return surf
    filename = name + ".png"
    if assets.exists(filename):
        surf = assets.original(filename)
    else:
        if name not in _warned:
            _warned.add(name)
            print("[fx] no art for %s; drawing a procedural stand-in" % name)
        surf = _procedural(name)
        try:
            surf = surf.convert_alpha()
        except pygame.error:
            # No display yet (tooling, unit tests): an unconverted surface
            # blits correctly, just a little slower.
            pass
    _textures[name] = surf
    return surf


def _evict(cache: Dict[Any, pygame.Surface]) -> None:
    """Make room in a full surface cache by dropping the oldest half.

    Clearing the whole thing is the obvious implementation and the wrong one:
    at the limit, every particle in the next frame would miss, rebuild its
    surface and refill the cache, so the system would stutter hardest exactly
    when the most is happening. Python dicts keep insertion order, which makes
    "the oldest half" free to identify.
    """
    if len(cache) < _CACHE_LIMIT:
        return
    for key in list(cache)[:_CACHE_LIMIT // 2]:
        del cache[key]


def invalidate() -> None:
    """Drop cached textures, shared scaled sprites and every live system's
    draw variants. Call alongside `assets.invalidate_scaled()` when the
    viewport changes.

    Live systems are reached through the weak registry rather than left to
    notice the generation bump on their next `draw()`. A system whose scene is
    not the one being drawn -- the menu's ambient layer while the game is up,
    or anything on a scene the app has left -- would otherwise sit on several
    MB of surfaces at a scale that no longer exists until the player happened
    to navigate back to it.
    """
    global _generation
    _generation += 1
    _textures.clear()
    ParticleSystem._shared_scaled.clear()
    # list(): a weak set can shrink mid-iteration if the GC runs.
    for system in list(_live):
        system._retire_surfaces()


