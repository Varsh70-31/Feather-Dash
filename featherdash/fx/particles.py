class _Particle:
    """One pooled particle. Plain slots, never reallocated."""

    __slots__ = (
        "x", "y", "vx", "vy", "ax", "ay", "drag",
        "rot", "spin", "age", "life",
        "size0", "size1", "r0", "g0", "b0", "r1", "g1", "b1",
        "a0", "a1", "fade_in", "sprite", "additive", "ease_size", "ease_alpha",
    )

    def __init__(self) -> None:
        self.x = self.y = 0.0
        self.vx = self.vy = 0.0
        self.ax = self.ay = 0.0
        self.drag = 0.0
        self.rot = self.spin = 0.0
        self.age = 0.0
        self.life = 1.0
        self.size0 = self.size1 = 1.0
        self.r0 = self.g0 = self.b0 = 255
        self.r1 = self.g1 = self.b1 = 255
        self.a0 = 255.0
        self.a1 = 0.0
        self.fade_in = 0.0
        self.sprite = "fx_soft"
        self.additive = False
        self.ease_size: EaseFn = out_quad
        self.ease_alpha: EaseFn = linear


# Emission spec. `*_var` is always a symmetric +/- range around the base value.
# Angles are degrees with 0 = right and +90 = down, matching world axes.
_DEFAULTS: Dict[str, Any] = {
    "life": 0.6, "life_var": 0.0,
    "speed": 0.0, "speed_var": 0.0,
    "angle": 0.0, "angle_var": 0.0,
    "vx": 0.0, "vy": 0.0,
    "ax": 0.0, "ay": 0.0, "gravity": 0.0,
    "drag": 0.0,
    "radius": 0.0,
    "size": 24.0, "size_var": 0.0, "grow": 1.0,
    "color": (255, 255, 255), "color_end": None,
    "alpha": 255.0, "alpha_end": 0.0, "fade_in": 0.0,
    "rot": 0.0, "rot_var": 0.0, "spin": 0.0, "spin_var": 0.0,
    "sprite": "fx_soft",
    "additive": False,
    "ease_size": out_quad, "ease_alpha": linear,
}
_SPEC_KEYS = frozenset(_DEFAULTS)


class ParticleSystem:
    """A fixed-capacity pool of particles sharing one draw pass.

    One system per visual layer is the intended usage (world particles behind
    the bird, UI particles above the HUD), because draw order is per system.
    """

    # Scaling is identical for every system at a given viewport, so the
    # expensive smoothscale results are shared process-wide.
    _shared_scaled: Dict[Tuple[str, int], pygame.Surface] = {}

    def __init__(self, capacity: int = 384, seed: Optional[int] = None) -> None:
        self.capacity = max(1, int(capacity))
        self._pool: List[_Particle] = [_Particle() for _ in range(self.capacity)]
        self._count = 0
        self._cursor = 0
        self._rng = random.Random(seed)
        self._variants: Dict[Tuple[Any, ...], pygame.Surface] = {}
        self._cache_scale = 0.0
        self._cache_generation = _generation
        _live.add(self)

    def _retire_surfaces(self) -> None:
        """Drop this system's derived surfaces now rather than on its next
        `draw()`, which for an off-screen scene may never come."""
        self._variants.clear()
        self._cache_generation = _generation

    # -- state -------------------------------------------------------------
    @property
    def active(self) -> int:
        return self._count

    def __len__(self) -> int:
        return self._count

    def clear(self) -> None:
        self._count = 0

    # -- emission ----------------------------------------------------------
    def _claim(self) -> _Particle:
        if self._count < self.capacity:
            p = self._pool[self._count]
            self._count += 1
            return p
        # Saturated. Steal the particle closest to the end of its life -- the
        # one whose disappearance is least noticeable -- rather than growing
        # the pool (an allocation spike at the worst moment) or dropping the
        # emission (effects that silently thin out under load).
        #
        # The candidates are a rotating window rather than the whole pool:
        # scanning every slot for every spawned particle is O(capacity) per
        # particle, which at 400 slots costs more than everything else the
        # system does in a frame. The window advances, so nothing just emitted
        # is stolen back, and the oldest of sixteen is visually the oldest.
        count = self._count
        start = self._cursor
        best_i = start % count
        best = -1.0
        for k in range(_RECYCLE_SAMPLE if count > _RECYCLE_SAMPLE else count):
            i = (start + k) % count
            p = self._pool[i]
            progress = p.age / p.life if p.life > 0.0 else 1.0
            if progress > best:
                best = progress
                best_i = i
        self._cursor = (best_i + 1) % count
        return self._pool[best_i]

    def emit(self, x: float, y: float, count: int = 1, **spec: Any) -> int:
        """Spawn `count` particles at world position (x, y).

        Returns the number spawned. Unknown spec keys raise, because a silently
        ignored typo in a preset is a bug that only shows up as "the effect
        looks wrong" months later.
        """
        unknown = set(spec) - _SPEC_KEYS
        if unknown:
            raise ValueError("unknown particle spec keys: " + ", ".join(sorted(unknown)))

        count = int(count)
        if count <= 0:
            return 0

        g = spec.get
        rng = self._rng
        uniform = rng.uniform

        life = float(g("life", 0.6))
        life_var = float(g("life_var", 0.0))
        speed = float(g("speed", 0.0))
        speed_var = float(g("speed_var", 0.0))
        angle = float(g("angle", 0.0))
        angle_var = float(g("angle_var", 0.0))
        base_vx = float(g("vx", 0.0))
        base_vy = float(g("vy", 0.0))
        ax = float(g("ax", 0.0))
        ay = float(g("ay", 0.0)) + float(g("gravity", 0.0))
        drag = max(0.0, float(g("drag", 0.0)))
        radius = float(g("radius", 0.0))
        size = float(g("size", 24.0))
        size_var = float(g("size_var", 0.0))
        grow = float(g("grow", 1.0))
        color = g("color", (255, 255, 255))
        color_end = g("color_end", None) or color
        alpha = float(g("alpha", 255.0))
        alpha_end = float(g("alpha_end", 0.0))
        fade_in = clamp01(float(g("fade_in", 0.0)))
        rot = float(g("rot", 0.0))
        rot_var = float(g("rot_var", 0.0))
        spin = float(g("spin", 0.0))
        spin_var = float(g("spin_var", 0.0))
        sprite = str(g("sprite", "fx_soft"))
        additive = bool(g("additive", False))
        ease_size = g("ease_size", out_quad)
        ease_alpha = g("ease_alpha", linear)

        r0, g0, b0 = int(color[0]), int(color[1]), int(color[2])
        r1, g1, b1 = int(color_end[0]), int(color_end[1]), int(color_end[2])

        for _ in range(count):
            p = self._claim()
            if radius > 0.0:
                # Square-root keeps the scatter uniform over the disc; without
                # it every burst clumps at its own centre.
                rr = radius * math.sqrt(rng.random())
                aa = uniform(0.0, math.tau)
                p.x = x + math.cos(aa) * rr
                p.y = y + math.sin(aa) * rr
            else:
                p.x = x
                p.y = y

            sp = speed + (uniform(-speed_var, speed_var) if speed_var else 0.0)
            an = math.radians(angle + (uniform(-angle_var, angle_var) if angle_var else 0.0))
            p.vx = base_vx + math.cos(an) * sp
            p.vy = base_vy + math.sin(an) * sp
            p.ax = ax
            p.ay = ay
            p.drag = drag

            p.rot = rot + (uniform(-rot_var, rot_var) if rot_var else 0.0)
            p.spin = spin + (uniform(-spin_var, spin_var) if spin_var else 0.0)

            p.age = 0.0
            p.life = max(1e-3, life + (uniform(-life_var, life_var) if life_var else 0.0))

            s = max(0.1, size + (uniform(-size_var, size_var) if size_var else 0.0))
            p.size0 = s
            # `grow` is a multiplier rather than an absolute end size so that
            # per-particle size variation survives to the end of the life.
            p.size1 = s * grow

            p.r0, p.g0, p.b0 = r0, g0, b0
            p.r1, p.g1, p.b1 = r1, g1, b1
            p.a0 = alpha
            p.a1 = alpha_end
            p.fade_in = fade_in
            p.sprite = sprite
            p.additive = additive
            p.ease_size = ease_size
            p.ease_alpha = ease_alpha
        return count

    def emit_preset(self, name: str, x: float, y: float, **overrides: Any) -> int:
        """Emit a named preset. Overrides apply to *every* layer of it.

        `count` replaces each layer's count; `count_scale` multiplies it, which
        is the usual way to dial an effect up for a milestone without editing
        the preset.
        """
        layers = PRESETS.get(name)
        if layers is None:
            raise KeyError("unknown particle preset: " + name)
        count_scale = float(overrides.pop("count_scale", 1.0))
        count_override = overrides.pop("count", None)
        total = 0
        for layer in layers:
            spec = dict(layer)
            n = int(count_override) if count_override is not None else int(spec.pop("count", 1))
            spec.pop("count", None)
            spec.update(overrides)
            total += self.emit(x, y, max(0, int(round(n * count_scale))), **spec)
        return total

    # -- simulation --------------------------------------------------------
    def update(self, dt: float) -> None:
        if dt <= 0.0 or self._count == 0:
            return
        pool = self._pool
        i = 0
        count = self._count
        while i < count:
            p = pool[i]
            p.age += dt
            if p.age >= p.life:
                # Swap-remove: O(1), and because the pool holds references the
                # dead object stays alive in the tail ready to be reused.
                count -= 1
                pool[i], pool[count] = pool[count], pool[i]
                continue
            p.vx += p.ax * dt
            p.vy += p.ay * dt
            if p.drag:
                # Exponential, not `v *= 0.98`: the same reason approach()
                # exists. A per-frame factor would make drag frame-rate bound.
                f = math.exp(-p.drag * dt)
                p.vx *= f
                p.vy *= f
            p.x += p.vx * dt
            p.y += p.vy * dt
            if p.spin:
                p.rot += p.spin * dt
            i += 1
        self._count = count
        if self._cursor >= count:
            self._cursor = 0

    # -- drawing -----------------------------------------------------------
    @staticmethod
    def _quantise_size(px: float) -> int:
        """Snap a pixel size to a bucket so the scaled-surface cache stays
        small. Steps widen with size, where a few pixels stop being visible."""
        if px <= 32.0:
            step = 4
        elif px <= 96.0:
            step = 8
        elif px <= 192.0:
            step = 16
        else:
            step = 32
        return max(4, int(round(px / step)) * step)

    def _scaled(self, sprite: str, px: int) -> pygame.Surface:
        key = (sprite, px)
        surf = ParticleSystem._shared_scaled.get(key)
        if surf is not None:
            return surf
        base = _texture(sprite)
        bw, bh = base.get_size()
        target = (px, max(1, int(round(px * bh / max(1, bw)))))
        surf = base if base.get_size() == target else pygame.transform.smoothscale(base, target)
        _evict(ParticleSystem._shared_scaled)
        ParticleSystem._shared_scaled[key] = surf
        return surf

    def _variant(
        self,
        sprite: str,
        px: int,
        color: Tuple[int, int, int],
        rot_bucket: float,
        additive: bool,
    ) -> pygame.Surface:
        key = (sprite, px, color[0], color[1], color[2], rot_bucket, additive)
        surf = self._variants.get(key)
        if surf is not None:
            return surf

        out = self._scaled(sprite, px).copy()
        out.fill((color[0], color[1], color[2], 255), special_flags=pygame.BLEND_RGBA_MULT)
        if additive:
            # BLEND_RGB_ADD ignores the source alpha channel, so a sprite whose
            # shape lives in its alpha would add as a solid square. Compositing
            # it over black first folds the shape into the RGB (premultiplied),
            # which is exactly what an additive blit wants.
            flat = pygame.Surface(out.get_size())
            flat.fill((0, 0, 0))
            flat.blit(out, (0, 0))
            out = flat
        if rot_bucket:
            # pygame rotates counter-clockwise; world y points down, so a
            # positive (clockwise on screen) spin is a negative pygame angle.
            out = pygame.transform.rotate(out, -rot_bucket)

        _evict(self._variants)
        self._variants[key] = out
        return out

    def draw(
        self,
        surface: pygame.Surface,
        viewport: "Viewport",
        offset: Tuple[float, float] = (0.0, 0.0),
    ) -> int:
        """Draw every live particle. Returns how many were actually blitted.

        `offset` is a world-unit shift (the camera) applied at draw time only,
        so a shaking camera never corrupts the simulation.
        """
        if self._count == 0:
            return 0
        if viewport.scale != self._cache_scale or self._cache_generation != _generation:
            # A resize (or an explicit invalidate) retires every pre-scaled,
            # pre-tinted surface this system is holding.
            self._variants.clear()
            self._cache_scale = viewport.scale
            self._cache_generation = _generation

        ox, oy = offset
        scale = viewport.scale
        orig_x = viewport.origin_x
        orig_y = viewport.origin_y
        left, right = viewport.view_left, viewport.view_right
        top, bottom = viewport.view_top, viewport.view_bottom
        add_flag = pygame.BLEND_RGB_ADD
        blit = surface.blit
        drawn = 0

        for i in range(self._count):
            p = self._pool[i]
            t = p.age / p.life
            if t > 1.0:
                t = 1.0

            a = p.a0 + (p.a1 - p.a0) * p.ease_alpha(t)
            if p.fade_in > 0.0 and t < p.fade_in:
                a *= t / p.fade_in
            if a <= 1.0:
                continue

            size_u = p.size0 + (p.size1 - p.size0) * p.ease_size(t)
            if size_u <= 0.0:
                continue
            half = size_u * 0.5

            wx = p.x + ox
            wy = p.y + oy
            # Cull against the real visible bounds (which include overscan),
            # not the play area, or particles pop out at the edge of a wide
            # screen where the backdrop is still showing.
            if wx + half < left or wx - half > right or wy + half < top or wy - half > bottom:
                continue

            px = self._quantise_size(size_u * scale)
            if px < 2:
                continue

            if a > 255.0:
                a = 255.0
            ia = int(a)

            if p.r0 == p.r1 and p.g0 == p.g1 and p.b0 == p.b1:
                cr, cg, cb = p.r0, p.g0, p.b0
            else:
                cr = int(p.r0 + (p.r1 - p.r0) * t)
                cg = int(p.g0 + (p.g1 - p.g0) * t)
                cb = int(p.b0 + (p.b1 - p.b0) * t)

            if p.additive:
                # Additive blending has no alpha term, so the fade has to be
                # baked into the colour itself.
                f = ia / 255.0
                cr = int(cr * f)
                cg = int(cg * f)
                cb = int(cb * f)
                if cr < 2 and cg < 2 and cb < 2:
                    continue

            quant = (
                min(255, ((cr + _COLOR_STEP // 2) // _COLOR_STEP) * _COLOR_STEP),
                min(255, ((cg + _COLOR_STEP // 2) // _COLOR_STEP) * _COLOR_STEP),
                min(255, ((cb + _COLOR_STEP // 2) // _COLOR_STEP) * _COLOR_STEP),
            )
            rot_bucket = (round(p.rot / _ROT_STEP) * _ROT_STEP) % 360.0 if p.rot else 0.0
            surf = self._variant(p.sprite, px, quant, rot_bucket, p.additive)

            sw, sh = surf.get_size()
            sx = int(orig_x + wx * scale - sw * 0.5)
            sy = int(orig_y + wy * scale - sh * 0.5)

            if p.additive:
                blit(surf, (sx, sy), None, add_flag)
            else:
                surf.set_alpha(ia)
                blit(surf, (sx, sy))
            drawn += 1
        return drawn


